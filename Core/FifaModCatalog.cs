using System.Text;
using ZstdSharp;
using static ATLink.Core.FifaModFile;

namespace ATLink.Core;

/// <summary>Reads only the legacy catalog from an FET cache v4. The large EBX/RES
/// prefix is streamed past, rather than retained in memory or shipped with ATLink.</summary>
public sealed class FifaModCatalog
{
    readonly Dictionary<ulong,FifaModCollector> files;
    readonly FifaModCollector launch;
    public byte[] GameBuild {get;}
    public uint NewChunkSuperBundle {get;}
    FifaModCatalog(byte[] build,FifaModCollector launch,Dictionary<ulong,FifaModCollector> files)
    {GameBuild=build;NewChunkSuperBundle=launch.SuperBundle;this.launch=launch;this.files=files;}

    public FifaModCollector Resolve(string gamePath)
    {
        gamePath=NormalizePath(gamePath);
        if(files.TryGetValue(NameHash(gamePath),out var collector))return collector;
        if(IsSupportedAddition(gamePath))return launch;
        throw new InvalidDataException("Resource not found in the FC27 cache: "+gamePath+". Refresh the cache in FIFA Editor Tool.");
    }

    internal bool IsAdded(string gamePath)=>!files.ContainsKey(NameHash(gamePath));

    public static FifaModCatalog Read(string path,IEnumerable<string> requiredPaths)
    {
        if(!Path.GetFileName(path).Equals("fc27.cache",StringComparison.OrdinalIgnoreCase))throw new InvalidDataException("Select the fc27.cache file generated by FIFA Editor Tool for this game installation.");
        var wanted=requiredPaths.Select(NormalizePath).ToDictionary(NameHash,p=>p);
        using var file=File.OpenRead(path);using var reader=new BinaryReader(file,Encoding.UTF8,true);
        if(!Exact(reader,4).AsSpan().SequenceEqual("FETC"u8)||reader.ReadByte()!=4)throw new InvalidDataException("Unsupported FIFA Editor Tool cache. Expected FETC version 4.");
        byte[] build=Exact(reader,7);Exact(reader,16);
        int bodySize=Positive(reader.ReadInt32(),1_000_000_000),blockSize=Positive(reader.ReadInt32(),1_000_000);
        int bundles=Nonnegative(reader.ReadInt32(),5_000_000),ebx=Nonnegative(reader.ReadInt32(),5_000_000),res=Nonnegative(reader.ReadInt32(),5_000_000),chunks=Nonnegative(reader.ReadInt32(),5_000_000),legacy=Nonnegative(reader.ReadInt32(),5_000_000),refs=Nonnegative(reader.ReadInt32(),1_000_000);
        int types=reader.ReadInt32(),ebxStart=reader.ReadInt32(),resStart=reader.ReadInt32(),chunkStart=reader.ReadInt32(),tailStart=reader.ReadInt32(),legacyStart=reader.ReadInt32();
        if(types<0||ebxStart<types||resStart<ebxStart||chunkStart<resStart||tailStart<chunkStart||legacyStart<tailStart||legacyStart>bodySize||legacyStart-tailStart>64*1024*1024)
            throw new InvalidDataException("Invalid cache section bounds.");
        foreach(int count in new[]{ebx,res,chunks,legacy})
            for(int i=0;i<(count+blockSize-1)/blockSize;i++)
                if(reader.ReadUInt32()>bodySize)throw new InvalidDataException("Invalid cache block offset.");
        using var decompressed=new DecompressionStream(file,leaveOpen:true);
        Skip(decompressed,tailStart);
        byte[] tail=new byte[legacyStart-tailStart];decompressed.ReadExactly(tail);
        using var tailStream=new MemoryStream(tail);using var t=new BinaryReader(tailStream,Encoding.UTF8,true);
        Skip(tailStream,checked(refs*20));
        int typeCount=Count(t,1_000_000);
        for(int i=0;i<typeCount;i++)
        {
            int length=0;while(t.ReadByte()!=0)if(++length>65536)throw new InvalidDataException("Invalid cache type name.");
            Exact(t,20);
        }
        int chunkIds=Count(t,5_000_000);Skip(tailStream,checked(chunkIds*16));
        int collectorCount=Count(t,256);var collectors=new FifaModCollector[collectorCount];
        for(int i=0;i<collectors.Length;i++)collectors[i]=new(ReadString(t),new Guid(Exact(t,16)),t.ReadUInt32());
        if(tailStream.Position!=tailStream.Length)throw new InvalidDataException("Unexpected cache collector layout.");
        var launch=collectors.SingleOrDefault(c=>c.Name.Equals("core/chunkfiles/launch/cfc_gm_launch",StringComparison.OrdinalIgnoreCase))
            ??throw new InvalidDataException("The FC27 launch collector is absent from this cache.");
        using var entries=new BinaryReader(decompressed,Encoding.UTF8,true);
        var found=new Dictionary<ulong,FifaModCollector>();
        for(int i=0;i<legacy;i++)
        {
            ulong hash=entries.ReadUInt64();Exact(entries,20);
            Count(entries,int.MaxValue);Count(entries,int.MaxValue);Count(entries,int.MaxValue);int chunkIndex=Count(entries,Math.Max(0,chunkIds-1));
            byte collector=entries.ReadByte();
            if(collector>=collectors.Length||chunkIds==0)throw new InvalidDataException("Invalid cache legacy reference.");
            if(wanted.ContainsKey(hash)&&!found.TryAdd(hash,collectors[collector]))throw new InvalidDataException("Duplicate game resource in cache.");
        }
        if(decompressed.ReadByte()!=-1)throw new InvalidDataException("Unexpected data after the cache legacy catalog.");
        var result=new FifaModCatalog(build,launch,found);
        foreach(string required in wanted.Values)result.Resolve(required);
        return result;
    }

    static int Positive(int n,int max)=>n>0&&n<=max?n:throw new InvalidDataException("Invalid cache size.");
    static int Nonnegative(int n,int max)=>n>=0&&n<=max?n:throw new InvalidDataException("Invalid cache count.");
    static void Skip(Stream stream,int bytes)
    {
        byte[] buffer=new byte[Math.Min(81920,Math.Max(1,bytes))];
        while(bytes>0){int n=Math.Min(bytes,buffer.Length);stream.ReadExactly(buffer.AsSpan(0,n));bytes-=n;}
    }
}
